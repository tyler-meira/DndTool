export function emptySheet(): CharacterSheet {
  return {
    name: "",
    portrait: "",
    className: "",
    species: "",
    background: "",
    alignment: "",
    level: "",
    abilities: { str: "", dex: "", con: "", int: "", wis: "", cha: "" },
    savingThrows: [],
    skills: Object.fromEntries(SKILLS.map(({ name }) => [name, 0])) as Record<SkillName, SkillRank>,
    hpCurrent: "",
    hpMax: "",
    tempHp: "",
    armorClass: "",
    speed: "",
    inspiration: false,
    deathSuccess: 0,
    deathFailure: 0,
    attacks: [],
    hitDice: "",
    gold: "",
    spells: "",
    features: "",
    equipment: "",
    notes: "",
  };
}

type LooseRecord = Record<string, unknown>;
function record(value: unknown): LooseRecord {
  return value && typeof value === "object" && !Array.isArray(value) ? value as LooseRecord : {};
}
function str(value: unknown, max = 20000): string {
  return typeof value === "string" ? value.slice(0, max) : typeof value === "number" && Number.isFinite(value) ? String(value) : "";
}
function int(value: unknown, max: number) {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? Math.min(max, Math.max(0, Math.round(parsed))) : 0;
}

// Normalizes data from Supabase and imports older VentureSheet backups too.
// No sample character or numeric defaults are ever inserted.
export function normalizeSheet(raw: unknown): CharacterSheet {
  const input = record(raw);
  const blank = emptySheet();
  const abilities = record(input.abilities);
  const skills = record(input.skills);
  const base = { ...blank };
  // Only accept browser-displayable images generated by the portrait uploader.
  if (typeof input.portrait === "string" && /^data:image\/(?:jpeg|png|webp);base64,[A-Za-z0-9+/=]+$/.test(input.portrait) && input.portrait.length <= 900000) {
    base.portrait = input.portrait;
  }
  const shortFields = ["name", "className", "species", "background", "alignment", "level", "hpCurrent", "hpMax", "tempHp", "armorClass", "speed", "hitDice", "gold"] as const;
  const longFields = ["features", "equipment", "spells", "notes"] as const;
  for (const field of shortFields) base[field] = str(input[field], field === "name" ? 160 : 200);
  for (const field of longFields) base[field] = str(input[field], 20000);
  for (const { id } of ABILITIES) base.abilities[id] = str(abilities[id], 3);
  const rawSaves: unknown[] = Array.isArray(input.savingThrows) ? input.savingThrows : [];
  base.savingThrows = ABILITIES.filter(({ id }) => rawSaves.includes(id)).map(({ id }) => id);
  for (const { name } of SKILLS) base.skills[name] = int(skills[name], 2) as SkillRank;
  base.inspiration = input.inspiration === true;
  base.deathSuccess = int(input.deathSuccess, 3);
  base.deathFailure = int(input.deathFailure, 3);
  base.attacks = Array.isArray(input.attacks)
    ? input.attacks.slice(0, 60).map((rawAttack) => {
        const a = record(rawAttack);
        return {
          id: typeof a.id === "string" && a.id ? a.id : crypto.randomUUID(),
          name: str(a.name, 140),
          toHit: str(a.toHit ?? a.attackBonus, 40),
          damage: str(a.damage, 200),
        };
      })
    : [];
  return base;
}

export function normalizeDbCharacter(raw: unknown): DbCharacter {
  const item = record(raw);
  return {
    id: str(item.id),
    user_id: str(item.user_id),
    name: str(item.name, 160),
    sheet: normalizeSheet(item.sheet),
    created_at: str(item.created_at),
    updated_at: str(item.updated_at),
  };
}

export function abilityModifier(score: string): number | null {
  if (!score.trim()) return null;
  const n = Number(score);
  if (!Number.isFinite(n) || n < 1 || n > 30) return null;
  return Math.floor((n - 10) / 2);
}

export function proficiencyBonus(level: string): number | null {
  if (!level.trim()) return null;
  const n = Number(level);
  if (!Number.isInteger(n) || n < 1 || n > 20) return null;
  return 2 + Math.floor((n - 1) / 4);
}

export function checkBonus(score: string, rank: number, level: string): number | null {
  const mod = abilityModifier(score);
  if (mod === null) return null;
  if (rank === 0) return mod;
  const prof = proficiencyBonus(level);
  return prof === null ? null : mod + prof * rank;
}

export function signed(value: number | null): string {
  return value === null ? "—" : value >= 0 ? `+${value}` : String(value);
}

export function characterTitle(character: Pick<DbCharacter, "sheet">) {
  return character.sheet.name.trim() || "Untitled character";
}
